import React, { useState, useEffect } from 'react';
import { Sparkles, ArrowRight, Loader2, RefreshCw, Lock, Stethoscope } from 'lucide-react';
import { motion, AnimatePresence } from 'framer-motion';
import { useNavigate } from 'react-router-dom';
import { usePetProfile } from '../hooks/usePetProfile';
import { GoogleGenAI } from '@google/genai';
import Markdown from 'react-markdown';

const apiKey = (import.meta as any).env.VITE_GEMINI_API_KEY;
let genAI: GoogleGenAI;
if (apiKey) {
  genAI = new GoogleGenAI({ apiKey });
}

const generateRoadmapText = async (formData: any) => {
  if (!genAI) {
    throw new Error('Gemini API Key missing');
  }
  const model = genAI.models;
  
  const prompt = `You are an elite, autonomous veterinary research agent. Your task is to generate a deeply contextual, living health roadmap for a pet based on their specific profile, medical history, and surgical history. 
CRITICAL RULES:
1. Formatting: NEVER use 'Months 1-3'. Strictly use '1-3 Months', '3-6 Months', etc.
2. Depth: Do not provide generic advice. Provide highly specific, actionable veterinary protocols based on the pet's breed and provided medical/surgical history.
3. Live Research: Use your Google Search tool to find the absolute latest veterinary best practices, studies, or nutritional guidelines relevant to this specific pet's condition. Research specifically based on the pet's history of: ${formData.medicalHistory || 'None'} and ${formData.surgicalHistory || 'None'}.
4. Citations: At the absolute bottom of the roadmap, you MUST include a 'Sources & Literature' section with valid external URLs so the pet parent can read the research themselves. Format the output in clean, professional Markdown.

Pet Profile:
Name: ${formData.name}
Species: ${formData.species}
Breed: ${formData.breed}
Age: ${formData.age} years old
Medical History/Issues: ${formData.medicalHistory || formData.issues || 'None reported'}
Surgical History: ${formData.surgicalHistory || 'None reported'}`;

  const response = await model.generateContent({
    model: "gemini-2.5-flash",
    contents: prompt,
    config: {
      tools: [{ googleSearch: {} }]
    }
  });

  return response.text || "Failed to generate roadmap.";
};

export default function Roadmap() {
  const navigate = useNavigate();
  const { profile, loading: profileLoading } = usePetProfile();
  
  const isProfileIncomplete = !profile?.petName && !profile?.name;

  const [formData, setFormData] = useState({ 
    name: profile?.petName || profile?.name || '', 
    species: 'Dog', 
    breed: profile?.petType || profile?.breed || '', 
    age: profile?.age || '5', 
    issues: profile?.healthHistory || '',
    medicalHistory: profile?.medicalHistory || '',
    surgicalHistory: profile?.surgicalHistory || ''
  });
  const [loading, setLoading] = useState(false);
  const [roadmap, setRoadmap] = useState<string | null>(null);
  const [error, setError] = useState('');
  const [hasAutoGenerated, setHasAutoGenerated] = useState(false);

  useEffect(() => {
    if (!isProfileIncomplete && !roadmap && !loading && !hasAutoGenerated) {
      const autoGenerate = async () => {
        setLoading(true);
        setHasAutoGenerated(true);
        
        const currentData = {
          name: profile?.petName || profile?.name || '',
          species: 'Dog',
          breed: profile?.petType || profile?.breed || '',
          age: profile?.age || '5',
          issues: profile?.healthHistory || '',
          medicalHistory: profile?.medicalHistory || '',
          surgicalHistory: profile?.surgicalHistory || ''
        };
        setFormData(currentData);

        try {
          setRoadmap(await generateRoadmapText(currentData));
        } catch (err: any) {
          setError(err.message || 'Failed to generate roadmap.');
        } finally {
          setLoading(false);
        }
      };
      autoGenerate();
    }
  }, [isProfileIncomplete, roadmap, loading, hasAutoGenerated, profile]);

  const handleInputChange = (e: any) => setFormData(prev => ({ ...prev, [e.target.name]: e.target.value }));

  const handleSubmit = async (e: any) => {
    e.preventDefault();
    if (!formData.name || !formData.breed || !formData.age) return setError('Please fill in Name, Breed, and Age.');
    
    setError('');
    setLoading(true);
    
    const latestData = {
      ...formData,
      medicalHistory: profile?.medicalHistory || '',
      surgicalHistory: profile?.surgicalHistory || ''
    };
    
    try {
      setRoadmap(await generateRoadmapText(latestData));
    } catch (err: any) {
      setError(err.message || 'Failed to generate roadmap.');
    } finally {
      setLoading(false);
    }
  };

  const resetForm = () => {
    setRoadmap(null);
    setFormData({ 
      name: profile?.petName || profile?.name || '', 
      species: 'Dog', 
      breed: profile?.petType || profile?.breed || '', 
      age: profile?.age || '5', 
      issues: profile?.healthHistory || '',
      medicalHistory: profile?.medicalHistory || '',
      surgicalHistory: profile?.surgicalHistory || ''
    });
  };

  if (profileLoading) {
    return (
      <div className="h-full w-full flex flex-col items-center justify-center p-6 pb-32">
        <Loader2 className="w-10 h-10 text-[#fec708] animate-spin mb-4" />
        <p className="text-white/60 font-medium">Loading pet profile...</p>
      </div>
    );
  }

  if (isProfileIncomplete) {
    return (
      <div className="h-full w-full flex flex-col items-center justify-center p-6 pb-32">
        <motion.div 
          initial={{ opacity: 0, y: 20 }}
          animate={{ opacity: 1, y: 0 }}
          className="relative z-10 bg-white/80 dark:bg-white/[0.03] backdrop-blur-xl dark:backdrop-blur-[24px] border border-slate-200 dark:border-white/[0.08] shadow-sm dark:shadow-[inset_0_1px_1px_rgba(255,255,255,0.05),0_8px_32px_rgba(0,0,0,0.4)] rounded-[2rem] p-10 max-w-md w-full text-center flex flex-col items-center"
        >
          <div className="w-24 h-24 bg-[#fec708]/20 rounded-full flex items-center justify-center mb-6 shadow-[0_0_30px_rgba(254,199,8,0.3)] border border-[#fec708]/50">
            <Lock className="w-10 h-10 text-[#fec708]" />
          </div>
          <h2 className="font-heading font-extrabold text-2xl text-slate-900 dark:text-white mb-3">Profile Incomplete</h2>
          <p className="font-body font-medium text-slate-600 dark:text-slate-300 mb-8 leading-relaxed">
            A complete profile is required to unlock the personalized Longevity Roadmap for your pet.
          </p>
          <button 
            onClick={() => navigate('/settings')}
            className="w-full bg-gradient-to-r from-[#fec708] to-[#fec708] text-black py-4 rounded-xl font-bold shadow-[0_0_20px_rgba(254,199,8,0.4)] hover:scale-[1.02] active:scale-95 transition-all"
          >
            Update Profile
          </button>
        </motion.div>
      </div>
    );
  }

  return (
    <div className="h-full w-full flex flex-col pb-32">
      <AnimatePresence mode="wait">
        <motion.div
          key="roadmap-content"
            initial={{ opacity: 0 }}
            animate={{ opacity: 1 }}
            transition={{ duration: 0.6 }}
            className="relative z-10 max-w-2xl mx-auto w-full p-6"
          >
            <div className="bg-white/80 dark:bg-white/[0.03] backdrop-blur-xl dark:backdrop-blur-[24px] border border-slate-200 dark:border-white/[0.08] shadow-sm dark:shadow-[inset_0_1px_1px_rgba(255,255,255,0.05),0_8px_32px_rgba(0,0,0,0.4)] rounded-[2rem] overflow-hidden">
              <AnimatePresence mode="wait">
                {!roadmap ? (
                  <motion.div key="form" initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }} className="p-8 sm:p-10 flex-1 flex flex-col">
                    <div className="flex items-center gap-4 mb-8">
                      <div className="bg-[#fec708] p-3 rounded-xl shadow-[0_0_20px_rgba(254,199,8,0.3)]">
                        <Sparkles className="w-6 h-6 text-black" />
                      </div>
                      <div>
                        <h3 className="font-heading font-extrabold text-xl text-slate-900 dark:text-white">Longevity Roadmap</h3>
                        <p className="font-body font-medium text-slate-500 dark:text-slate-300 text-sm">Personalized health timeline</p>
                      </div>
                    </div>
                    
                    {error && (
                      <div className="mb-6 p-3 bg-red-50 text-red-600 dark:bg-red-500/20 dark:text-white backdrop-blur-md border border-red-200 dark:border-red-500/30 rounded-lg text-sm font-medium">
                        {error}
                      </div>
                    )}
                    
                    <form onSubmit={handleSubmit} className="flex-1 flex flex-col space-y-5">
                      <div className="grid grid-cols-2 gap-4">
                        <div>
                          <label className="block text-xs font-bold text-slate-500 dark:text-white/60 uppercase tracking-wider mb-2">Pet Name</label>
                          <input type="text" name="name" value={formData.name} onChange={handleInputChange} placeholder="e.g. Max" className="w-full px-4 py-3 rounded-xl border border-slate-200 dark:border-white/[0.08] focus:ring-2 focus:ring-[#fec708] focus:bg-white dark:focus:bg-white/[0.08] outline-none bg-white/50 dark:bg-white/[0.03] backdrop-blur-md text-slate-900 dark:text-white placeholder:text-slate-400 dark:placeholder:text-white/40 transition-all shadow-sm" />
                        </div>
                        <div>
                          <label className="block text-xs font-bold text-slate-500 dark:text-white/60 uppercase tracking-wider mb-2">Species</label>
                          <select name="species" value={formData.species} onChange={handleInputChange} className="w-full px-4 py-3 rounded-xl border border-slate-200 dark:border-white/[0.08] focus:ring-2 focus:ring-[#fec708] focus:bg-white dark:focus:bg-white/[0.08] outline-none bg-white/50 dark:bg-white/[0.03] backdrop-blur-md text-slate-900 dark:text-white transition-all shadow-sm dark:[&>option]:bg-neutral-900">
                            <option>Dog</option>
                            <option>Cat</option>
                            <option>Other</option>
                          </select>
                        </div>
                      </div>
                      
                      <div>
                        <label className="block text-xs font-bold text-slate-500 dark:text-white/60 uppercase tracking-wider mb-2">Breed</label>
                        <input type="text" name="breed" value={formData.breed} onChange={handleInputChange} placeholder="e.g. American Bully" className="w-full px-4 py-3 rounded-xl border border-slate-200 dark:border-white/[0.08] focus:ring-2 focus:ring-[#fec708] focus:bg-white dark:focus:bg-white/[0.08] outline-none bg-white/50 dark:bg-white/[0.03] backdrop-blur-md text-slate-900 dark:text-white placeholder:text-slate-400 dark:placeholder:text-white/40 transition-all shadow-sm" />
                      </div>
                      
                      <div className="grid grid-cols-2 gap-4">
                        <div>
                          <label className="block text-xs font-bold text-slate-500 dark:text-white/60 uppercase tracking-wider mb-2">Age (Years)</label>
                          <input type="number" name="age" value={formData.age} onChange={handleInputChange} placeholder="e.g. 5" min="0" step="0.1" className="w-full px-4 py-3 rounded-xl border border-slate-200 dark:border-white/[0.08] focus:ring-2 focus:ring-[#fec708] focus:bg-white dark:focus:bg-white/[0.08] outline-none bg-white/50 dark:bg-white/[0.03] backdrop-blur-md text-slate-900 dark:text-white placeholder:text-slate-400 dark:placeholder:text-white/40 transition-all shadow-sm" />
                        </div>
                        <div>
                          <label className="block text-xs font-bold text-slate-500 dark:text-white/60 uppercase tracking-wider mb-2">Known Issues</label>
                          <input type="text" name="issues" value={formData.issues} onChange={handleInputChange} placeholder="e.g. Joint pain" className="w-full px-4 py-3 rounded-xl border border-slate-200 dark:border-white/[0.08] focus:ring-2 focus:ring-[#fec708] focus:bg-white dark:focus:bg-white/[0.08] outline-none bg-white/50 dark:bg-white/[0.03] backdrop-blur-md text-slate-900 dark:text-white placeholder:text-slate-400 dark:placeholder:text-white/40 transition-all shadow-sm" />
                        </div>
                      </div>
                      
                      <button type="submit" disabled={loading} className="mt-auto w-full bg-gradient-to-r from-[#fec708] to-[#fec708] text-black py-4 rounded-xl font-bold flex justify-center items-center gap-2 shadow-[0_0_20px_rgba(254,199,8,0.4)] hover:scale-[1.02] active:scale-95 disabled:opacity-70 disabled:hover:scale-100 transition-all">
                        {loading ? (
                          <>
                            <Loader2 className="animate-spin w-5 h-5" /> Analyzing...
                          </>
                        ) : (
                          <>
                            Generate Profile <ArrowRight className="w-5 h-5" />
                          </>
                        )}
                      </button>
                    </form>
                  </motion.div>
                ) : (
                  <motion.div key="results" initial={{ opacity: 0 }} animate={{ opacity: 1 }} className="p-8 flex-1 flex flex-col space-y-6">
                    {/* Header */}
                    <div className="flex justify-between items-start border-b border-slate-200 dark:border-white/[0.08] pb-6">
                      <div>
                        <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-[#fec708]/20 text-[#fec708] text-xs font-bold mb-2 border border-[#fec708]/50 shadow-sm">
                          <Sparkles className="w-3 h-3" /> Roadmap Generated
                        </div>
                        <h2 className="font-heading font-extrabold text-2xl text-slate-900 dark:text-white">{formData.name}'s Plan</h2>
                      </div>
                      <button onClick={resetForm} className="p-2 text-slate-500 dark:text-white/60 hover:text-slate-900 dark:hover:text-white bg-white/50 dark:bg-white/[0.03] backdrop-blur-md border border-slate-200 dark:border-white/[0.08] rounded-full hover:bg-white dark:hover:bg-white/[0.08] transition-all shadow-sm" title="Start Over">
                        <RefreshCw size={18} />
                      </button>
                    </div>
                    
                    <div className="text-left text-slate-700 dark:text-white/90 leading-relaxed font-sans">
                      <Markdown
                        components={{
                          h1: ({node, ...props}) => <h1 className="font-heading font-extrabold text-2xl text-slate-900 dark:text-white mt-8 mb-4 tracking-tight" {...props} />,
                          h2: ({node, ...props}) => <h2 className="font-heading font-bold text-xl text-slate-900 dark:text-white mt-8 mb-3 tracking-tight border-b border-slate-200 dark:border-white/[0.08] pb-2" {...props} />,
                          h3: ({node, ...props}) => <h3 className="font-heading font-bold text-[#fec708] mt-6 mb-2 uppercase tracking-wide text-sm" {...props} />,
                          p: ({node, ...props}) => <p className="font-body text-base mb-4 text-slate-700 dark:text-slate-200" {...props} />,
                          ul: ({node, ...props}) => <ul className="list-disc pl-5 mb-4 space-y-2 opacity-90" {...props} />,
                          li: ({node, ...props}) => <li className="font-body text-slate-700 dark:text-slate-200" {...props} />,
                          strong: ({node, ...props}) => <strong className="font-bold text-slate-900 dark:text-white" {...props} />,
                          a: ({node, ...props}) => (
                            <a 
                              className="inline-flex items-center gap-1 font-medium text-[#fec708] hover:text-[#e5b307] bg-[#fec708]/10 hover:bg-[#fec708]/20 px-3 py-1 rounded-full text-sm transition-colors mt-1 break-all"
                              target="_blank" 
                              rel="noopener noreferrer" 
                              {...props} 
                            />
                          )
                        }}
                      >
                        {roadmap}
                      </Markdown>
                    </div>
                  </motion.div>
                )}
              </AnimatePresence>
            </div>
          </motion.div>
      </AnimatePresence>
    </div>
  );
}
